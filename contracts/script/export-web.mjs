#!/usr/bin/env node
// Exports compiled ABIs and the local deployment into web/lib/contracts/ for the front end.
//
//   node contracts/script/export-web.mjs [--rpc-url URL] [--chain-id N] [--out DIR] [--check]
//
// ABIs come from Foundry's artifacts in contracts/out/. Addresses come from the chain itself: only the two factory
// addresses are read from Forge's broadcast file, and everything else (the tokens and the market) is read back
// through the factories' registries. The broadcast must be complete (nothing pending, every receipt successful), the
// deployed bytecode must match the current build artifacts (so ABIs and addresses cannot drift apart), and the market
// must be the deployment's seed market. Nothing is written unless every check passes. No private key is read or needed.
// Requires `cast` (Foundry) on PATH and a prior `forge build` and `forge script ... --broadcast`.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const CONTRACTS_DIR = resolve(HERE, '..');
export const REPO_ROOT = resolve(CONTRACTS_DIR, '..');
export const DEFAULT_OUT_DIR = join(REPO_ROOT, 'web', 'lib', 'contracts');
export const DEFAULT_RPC_URL = 'http://127.0.0.1:8545';
export const DEFAULT_CHAIN_ID = 31337;

/** [export name, artifact name]. Artifacts live at out/<name>.sol/<name>.json. */
export const ABI_EXPORTS = [
  ['tokenFactoryAbi', 'TokenFactory'],
  ['demoTokenAbi', 'DemoToken'],
  ['marketFactoryAbi', 'MarketFactory'],
  ['orderBookAbi', 'OrderBook'],
];

const ADDRESS_RE = /^0x[0-9a-fA-F]{40}$/;
const HEADER =
  '// GENERATED by contracts/script/export-web.mjs. Do not edit by hand: rerun the exporter.\n' +
  '// ABIs are copied from Foundry artifacts (contracts/out). Addresses are read back from the chain.\n';

export class ExportError extends Error {}

export function isAddress(value) {
  return typeof value === 'string' && ADDRESS_RE.test(value);
}

function requireAddress(value, what) {
  if (!isAddress(value)) throw new ExportError(`${what} is not a valid address: ${JSON.stringify(value)}`);
  return value;
}

/**
 * Reads the two factory addresses and the first deployment block out of a Forge broadcast file.
 * Only top-level CREATE transactions are used. Tokens and the market are read from the chain instead.
 */
export function parseBroadcast(broadcast, chainId) {
  if (Number(broadcast?.chain) !== chainId) {
    throw new ExportError(`broadcast file is for chain ${broadcast?.chain}, expected ${chainId}`);
  }
  const txs = Array.isArray(broadcast.transactions) ? broadcast.transactions : [];
  const receipts = Array.isArray(broadcast.receipts) ? broadcast.receipts : [];

  // A half-finished deployment (interrupted, or a transaction that failed) must never be exported as if complete.
  const pending = Array.isArray(broadcast.pending) ? broadcast.pending.length : 0;
  if (pending > 0) throw new ExportError(`the broadcast file has ${pending} pending transaction(s): the deployment did not finish. Rerun the deploy script`);
  if (txs.length === 0 || receipts.length !== txs.length) {
    throw new ExportError(`the broadcast file has ${txs.length} transaction(s) but ${receipts.length} receipt(s): the deployment is incomplete. Rerun the deploy script`);
  }
  for (const tx of txs) {
    const receipt = receipts.find((r) => r.transactionHash === tx.hash);
    if (!receipt) throw new ExportError(`no receipt for transaction ${tx.hash}: the deployment is incomplete`);
    if (receipt.status !== '0x1' && receipt.status !== 1 && receipt.status !== true) {
      throw new ExportError(`transaction ${tx.hash} did not succeed (status ${receipt.status}): the deployment failed`);
    }
  }

  const find = (name) => {
    const hits = txs.filter((t) => t.transactionType === 'CREATE' && t.contractName === name);
    if (hits.length !== 1) throw new ExportError(`expected exactly one ${name} CREATE in the broadcast file, found ${hits.length}`);
    return hits[0];
  };
  const tokenFactoryTx = find('TokenFactory');
  const marketFactoryTx = find('MarketFactory');

  const tokenFactory = requireAddress(tokenFactoryTx.contractAddress, 'TokenFactory address');
  const marketFactory = requireAddress(marketFactoryTx.contractAddress, 'MarketFactory address');
  const deployer = requireAddress(tokenFactoryTx.transaction?.from, 'deployer address');

  const receipt = receipts.find((r) => r.transactionHash === tokenFactoryTx.hash);
  if (!receipt) throw new ExportError('no receipt for the TokenFactory deployment in the broadcast file');
  let deployBlock;
  try {
    deployBlock = Number(BigInt(receipt.blockNumber));
  } catch {
    throw new ExportError(`bad deployment block number: ${JSON.stringify(receipt.blockNumber)}`);
  }
  if (!Number.isSafeInteger(deployBlock) || deployBlock < 0) throw new ExportError('bad deployment block number');
  if (!/^0x[0-9a-fA-F]{64}$/.test(receipt.blockHash ?? '')) throw new ExportError('bad deployment block hash');

  return { deployer, tokenFactory, marketFactory, deployBlock, deployBlockHash: receipt.blockHash.toLowerCase() };
}

export function renderAbis(abis) {
  const body = ABI_EXPORTS.map(([exportName]) => {
    const abi = abis[exportName];
    if (!Array.isArray(abi)) throw new ExportError(`missing ABI for ${exportName}`);
    return `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  });
  return `${HEADER}\n${body.join('\n')}`;
}

export function renderDeployments(chainId, d) {
  const token = (t) =>
    `{ address: "${t.address}", name: ${JSON.stringify(t.name)}, symbol: ${JSON.stringify(t.symbol)}, decimals: ${t.decimals} }`;
  return (
    `${HEADER}\n` +
    `export const deployments = {\n` +
    `  ${chainId}: {\n` +
    `    chainId: ${chainId},\n` +
    `    deployBlock: ${d.deployBlock},\n` +
    `    deployer: "${d.deployer}",\n` +
    `    tokenFactory: "${d.tokenFactory}",\n` +
    `    marketFactory: "${d.marketFactory}",\n` +
    `    market: "${d.market}",\n` +
    `    baseToken: ${token(d.baseToken)},\n` +
    `    quoteToken: ${token(d.quoteToken)},\n` +
    `  },\n` +
    `} as const;\n\n` +
    `export type DeploymentChainId = keyof typeof deployments;\n`
  );
}

export function loadAbis(outDir = join(CONTRACTS_DIR, 'out')) {
  const abis = {};
  for (const [exportName, artifact] of ABI_EXPORTS) {
    const file = join(outDir, `${artifact}.sol`, `${artifact}.json`);
    if (!existsSync(file)) throw new ExportError(`missing artifact ${file}. Run \`forge build\` in contracts/ first`);
    const abi = JSON.parse(readFileSync(file, 'utf8')).abi;
    if (!Array.isArray(abi) || abi.length === 0) throw new ExportError(`artifact ${file} has no ABI`);
    abis[exportName] = abi;
  }
  return abis;
}

/** Deployed bytecode and immutable slots from the build artifacts, used to prove the chain runs the current build. */
export function loadDeployedBytecode(outDir = join(CONTRACTS_DIR, 'out')) {
  const names = ['TokenFactory', 'MarketFactory', 'OrderBook', 'DemoToken'];
  const result = {};
  for (const name of names) {
    const file = join(outDir, `${name}.sol`, `${name}.json`);
    if (!existsSync(file)) throw new ExportError(`missing artifact ${file}. Run \`forge build\` in contracts/ first`);
    const deployed = JSON.parse(readFileSync(file, 'utf8')).deployedBytecode;
    if (!deployed || typeof deployed.object !== 'string' || deployed.object.length < 4) {
      throw new ExportError(`artifact ${file} has no deployed bytecode`);
    }
    result[name] = { code: deployed.object, immutableReferences: deployed.immutableReferences ?? {} };
  }
  return result;
}

/** Zeroes the bytes that hold immutables, which differ per deployment (constructor arguments), in a 0x-hex string. */
export function maskImmutables(hex, immutableReferences = {}) {
  const chars = hex.toLowerCase().replace(/^0x/, '').split('');
  for (const refs of Object.values(immutableReferences)) {
    for (const { start, length } of refs) {
      for (let i = start * 2; i < (start + length) * 2 && i < chars.length; i++) chars[i] = '0';
    }
  }
  return `0x${chars.join('')}`;
}

export function bytecodeMatches(chainCode, artifact) {
  return maskImmutables(chainCode, artifact.immutableReferences) === maskImmutables(artifact.code, artifact.immutableReferences);
}

function redact(rpcUrl) {
  try {
    const u = new URL(rpcUrl);
    return `${u.protocol}//${u.host}`;
  } catch {
    return '(invalid url)';
  }
}

/** Thin wrapper around `cast`. No shell is involved, so arguments are never interpreted by one. */
export function makeCast(rpcUrl) {
  const run = (args) => {
    try {
      return execFileSync('cast', [...args, `--rpc-url=${rpcUrl}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
    } catch (error) {
      const detail = String(error.stderr || error.message).trim().split('\n').slice(-2).join(' ');
      throw new ExportError(`cast ${args[0]} failed (is Anvil running at ${redact(rpcUrl)}?): ${detail}`);
    }
  };
  const checksum = (addr) => {
    requireAddress(addr, 'address');
    return execFileSync('cast', ['to-check-sum-address', addr], { encoding: 'utf8' }).trim();
  };
  const callAddress = (to, sig, ...args) => checksum(run(['call', to, sig, ...args]));
  const callString = (to, sig) => {
    const out = run(['call', to, sig]);
    try {
      const value = JSON.parse(out);
      if (typeof value !== 'string') throw new Error('not a string');
      return value;
    } catch {
      throw new ExportError(`unexpected output from cast for ${sig} on ${to}: ${out.slice(0, 80)}`);
    }
  };
  return { run, checksum, callAddress, callString };
}

/** Reads and validates the live chain, and returns everything the front end needs. Throws before writing anything. */
function bytecodeMismatch(name, addr) {
  return `the bytecode of ${name} at ${addr} does not match the current build artifacts (contracts/out). The contracts changed since they were deployed. Redeploy, then export`;
}

export function collectDeployment({ broadcast, chainId, rpcUrl, bytecode, cast = makeCast(rpcUrl) }) {
  const parsed = parseBroadcast(broadcast, chainId);
  const c = cast;

  const liveChainId = Number(c.run(['chain-id']));
  if (liveChainId !== chainId) throw new ExportError(`RPC reports chain ${liveChainId}, expected ${chainId}`);

  // Stale-deployment detection: the block that held the deployment must still exist with the same hash.
  // The chain id call above already succeeded, so a failure here means the block is missing (a restarted chain).
  let liveHash;
  try {
    liveHash = c.run(['block', String(parsed.deployBlock), '--field', 'hash']).toLowerCase();
  } catch {
    throw new ExportError(
      `stale deployment: block ${parsed.deployBlock} does not exist on this chain (height ${c.run(['block-number'])}). ` +
        `The chain was restarted or replaced; run the deploy script again`,
    );
  }
  if (liveHash !== parsed.deployBlockHash) {
    throw new ExportError(
      `stale deployment: block ${parsed.deployBlock} on this chain is ${liveHash}, but the broadcast file recorded ` +
        `${parsed.deployBlockHash}. The chain was restarted or replaced; run the deploy script again`,
    );
  }

  const tokenFactory = c.checksum(parsed.tokenFactory);
  const marketFactory = c.checksum(parsed.marketFactory);
  for (const [what, addr] of [['TokenFactory', tokenFactory], ['MarketFactory', marketFactory]]) {
    const code = c.run(['code', addr]);
    if (code === '0x') throw new ExportError(`no contract code at ${what} ${addr}: stale deployment`);
    if (!bytecodeMatches(code, bytecode[what])) throw new ExportError(bytecodeMismatch(what, addr));
  }

  // The seed market is the factory's first. Its tokens are read back from the market itself.
  const marketList = c.run(['call', marketFactory, 'getMarkets(uint256,uint256)(address[])', '0', '1']);
  const market = (marketList.match(/0x[0-9a-fA-F]{40}/g) ?? [])[0];
  if (!market) throw new ExportError('MarketFactory has no markets: the deploy script did not create one');
  const marketAddr = c.checksum(market);
  const base = c.callAddress(marketAddr, 'baseToken()(address)');
  const quote = c.callAddress(marketAddr, 'quoteToken()(address)');

  // The deploy script issues the base token first and the quote token second, then creates the market from them. A market
  // made by someone else (for example in the opposite orientation) is not the seed market, even if it is registered.
  const issued = c.run(['call', tokenFactory, 'getTokens(uint256,uint256)(address[])', '0', '2']).match(/0x[0-9a-fA-F]{40}/g) ?? [];
  if (issued.length !== 2 || c.checksum(issued[0]) !== base || c.checksum(issued[1]) !== quote) {
    throw new ExportError('the first market is not built from the first two tokens issued by the TokenFactory (base first), so it is not the deployment script\'s seed market');
  }
  if (!bytecodeMatches(c.run(['code', marketAddr]), bytecode.OrderBook)) throw new ExportError(bytecodeMismatch('OrderBook', marketAddr));

  const truthy = (out) => out === 'true';
  if (!truthy(c.run(['call', marketFactory, 'isMarket(address)(bool)', marketAddr]))) throw new ExportError('market is not registered as a market');
  if (c.callAddress(marketFactory, 'getMarket(address,address)(address)', base, quote) !== marketAddr) {
    throw new ExportError('MarketFactory.getMarket(base, quote) does not return the market');
  }

  const describeToken = (address, role) => {
    const code = c.run(['code', address]);
    if (code === '0x') throw new ExportError(`no contract code at ${role} token ${address}`);
    if (!bytecodeMatches(code, bytecode.DemoToken)) throw new ExportError(bytecodeMismatch('DemoToken', address));
    if (!truthy(c.run(['call', tokenFactory, 'isFactoryToken(address)(bool)', address]))) {
      throw new ExportError(`${role} token ${address} was not issued by this TokenFactory`);
    }
    const decimals = Number(c.run(['call', address, 'decimals()(uint8)']).split(/\s/)[0]);
    if (decimals !== 18) throw new ExportError(`${role} token has ${decimals} decimals, expected 18`);
    return { address, name: c.callString(address, 'name()(string)'), symbol: c.callString(address, 'symbol()(string)'), decimals };
  };

  return {
    deployBlock: parsed.deployBlock,
    deployer: c.checksum(parsed.deployer),
    tokenFactory,
    marketFactory,
    market: marketAddr,
    baseToken: describeToken(base, 'base'),
    quoteToken: describeToken(quote, 'quote'),
  };
}

export function parseArgs(argv, env = process.env) {
  const opts = { rpcUrl: env.RPC_URL || DEFAULT_RPC_URL, chainId: DEFAULT_CHAIN_ID, outDir: DEFAULT_OUT_DIR, check: false, broadcastFile: null };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const value = () => {
      if (i + 1 >= argv.length) throw new ExportError(`${arg} needs a value`);
      return argv[++i];
    };
    if (arg === '--rpc-url') opts.rpcUrl = value();
    else if (arg === '--chain-id') opts.chainId = Number(value());
    else if (arg === '--out') opts.outDir = resolve(value());
    else if (arg === '--broadcast-file') opts.broadcastFile = resolve(value());
    else if (arg === '--check') opts.check = true;
    else throw new ExportError(`unknown argument ${arg}`);
  }
  if (!Number.isSafeInteger(opts.chainId) || opts.chainId <= 0) throw new ExportError('--chain-id must be a positive integer');
  let url;
  try {
    url = new URL(opts.rpcUrl);
  } catch {
    throw new ExportError(`--rpc-url is not a URL: ${opts.rpcUrl}`);
  }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') throw new ExportError('--rpc-url must be http or https');
  return opts;
}

/** Writes the files, or in check mode compares them with what is on disk. Returns what happened. Throws on stale files. */
export function applyFiles(files, outDir, check) {
  if (check) {
    const stale = Object.entries(files).filter(([name, text]) => {
      const file = join(outDir, name);
      return !existsSync(file) || readFileSync(file, 'utf8') !== text;
    });
    if (stale.length) throw new ExportError(`out of date: ${stale.map(([n]) => n).join(', ')}. Rerun the exporter`);
    return 'up-to-date';
  }
  mkdirSync(outDir, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(outDir, name), text);
  return 'written';
}

export function main(argv = process.argv.slice(2)) {
  const opts = parseArgs(argv);
  const broadcastFile = opts.broadcastFile ?? join(CONTRACTS_DIR, 'broadcast', 'Deploy.s.sol', String(opts.chainId), 'run-latest.json');
  if (!existsSync(broadcastFile)) {
    throw new ExportError(`no broadcast file at ${broadcastFile}. Run the deploy script with --broadcast first`);
  }

  const abis = loadAbis();
  let broadcast;
  try {
    broadcast = JSON.parse(readFileSync(broadcastFile, 'utf8'));
  } catch {
    throw new ExportError(`${broadcastFile} is not valid JSON`);
  }
  const deployment = collectDeployment({ broadcast, chainId: opts.chainId, rpcUrl: opts.rpcUrl, bytecode: loadDeployedBytecode() });
  const files = {
    'abis.ts': renderAbis(abis),
    'deployments.ts': renderDeployments(opts.chainId, deployment),
  };

  const result = applyFiles(files, opts.outDir, opts.check);
  if (result === 'up-to-date') {
    console.log(`export-web: ${Object.keys(files).join(', ')} are up to date for chain ${opts.chainId}`);
    return;
  }
  console.log(`export-web: wrote ${Object.keys(files).join(', ')} to ${opts.outDir}`);
  console.log(`  chain ${opts.chainId}, deploy block ${deployment.deployBlock}, market ${deployment.market}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    if (error instanceof ExportError) {
      console.error(`export-web: ${error.message}`);
      process.exit(1);
    }
    throw error;
  }
}
